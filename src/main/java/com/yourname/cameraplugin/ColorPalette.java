    /** Sky color (used when no block is hit). */
    private static final Color SKY_COLOR = new Color(100, 160, 240);

    /**
     * Returns the map palette byte for the given material and hit face,
     * applying Minecraft's 4-shade variant for directional lighting.
     */
    public static byte toMapColor(Material material, BlockFace face) {
        Color base = (material == null) ? SKY_COLOR
                : BLOCK_COLORS.getOrDefault(material, new Color(180, 180, 180));

        // The shade variant determines which of the 4 tones to pick:
        //   0 = dark, 1 = normal, 2 = light, 3 = lightest
        // matchColor() searches the full palette (all 4 × base_colors),
        // so we shift the input RGB to land in the right shade bucket.
        Color shaded = applyShade(base, face);
        return MapPalette.matchColor(shaded);
    }

    /**
     * Applies simple directional shading to a color by scaling its brightness
     * based on which block face was hit.
     *
     * Minecraft map shades (approximate multipliers relative to normal):
     *   Top    → 1.00 (normal)
     *   South/North → 0.80 (medium shade)
     *   East/West   → 0.65 (darker side)
     *   Bottom → 0.50 (darkest)
     */
    private static Color applyShade(Color base, BlockFace face) {
        double factor = switch (face) {
            case UP      -> 1.00;
            case SOUTH, NORTH -> 0.80;
            case EAST, WEST   -> 0.65;
            case DOWN   -> 0.50;
            default       -> 0.85;
        };

        int r = clamp((int)(base.getRed()   * factor));
        int g = clamp((int)(base.getGreen() * factor));
        int b = clamp((int)(base.getBlue()  * factor));
        return new Color(r, g, b);
    }

    public static Color getBaseColor(Material material) {
        return (material == null) ? SKY_COLOR
                : BLOCK_COLORS.getOrDefault(material, new Color(180, 180, 180));
    }

    private static int clamp(int v) {
        return Math.max(0, Math.min(255, v));
    }
